// Verify reCAPTCHA
//
// Called from index.html's registration form before a registration is
// accepted. reCAPTCHA runs invisibly here (score-based, no checkbox/puzzle —
// Google's own recommended default, since it's the least friction for the
// resident). This function holds the reCAPTCHA *secret* key server-side (it
// must never reach the browser) and asks Google whether a given token is
// genuine, and how likely the interaction was human.
//
// Requires one environment variable set in Netlify's dashboard for this site
// (Site configuration -> Environment variables) — NOT in any file in this
// repo:
//   RECAPTCHA_SECRET_KEY   The *legacy* secret key for the site key used in
//                          index.html, from the Google Cloud Fraud Defense
//                          console (Key details -> Integration tab ->
//                          "Integrate with a third-party service or
//                          plug-in" -> reveals this). This is deliberately
//                          NOT the modern Enterprise Assessment API — that
//                          would require a GCP project, API key/service
//                          account, and billing just for a low-volume
//                          visitor-parking form. The legacy secret key
//                          works with the plain siteverify endpoint below,
//                          same as any pre-Enterprise reCAPTCHA integration.
//
// The site key itself (public, in index.html) must be a Score-based key,
// registered for these domains: regentparking.ca (covers every
// *.regentparking.ca tenant subdomain automatically), dueastparking.netlify.app,
// and localhost (for local testing).

const ALLOWED_HOSTS = [
  /^localhost$/,
  /^127\.0\.0\.1$/,
  /^dueastparking\.netlify\.app$/,
  /^([a-z0-9-]+\.)?regentparking\.ca$/,
];

// Google scores each interaction 0.0 (bot) to 1.0 (human). There's no
// universally "correct" cutoff — it depends on the traffic Google's seen
// for this key. Start at 0.5 and tune from the score distribution on the
// key's Overview tab in the Google Cloud Fraud Defense console if real
// residents ever start getting rejected, or if spam gets through.
const MIN_SCORE = 0.5;

export default async (req) => {
  if (req.method !== 'POST') {
    return json({ error: 'Method not allowed' }, 405);
  }

  const SECRET_KEY = process.env.RECAPTCHA_SECRET_KEY;
  if (!SECRET_KEY) {
    return json({ error: 'Server is missing RECAPTCHA_SECRET_KEY. Set it in Netlify -> Site configuration -> Environment variables, then redeploy.' }, 500);
  }

  let body;
  try {
    body = await req.json();
  } catch {
    return json({ error: 'Invalid request body.' }, 400);
  }

  const token = (body.token || '').trim();
  const expectedAction = (body.action || '').trim();
  if (!token) {
    return json({ success: false, error: 'Missing reCAPTCHA token.' }, 400);
  }

  let verifyRes;
  try {
    verifyRes = await fetch('https://www.google.com/recaptcha/api/siteverify', {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: new URLSearchParams({ secret: SECRET_KEY, response: token }),
    });
  } catch {
    return json({ success: false, error: 'Could not reach Google to verify the security check. Please try again.' }, 502);
  }

  const result = await verifyRes.json().catch(() => null);
  if (!result?.success) {
    return json({ success: false, error: 'Security check failed. Please try again.' }, 200);
  }

  // Score-based keys return a 0.0-1.0 score instead of a plain pass/fail —
  // reject anything below the threshold.
  const score = typeof result.score === 'number' ? result.score : 0;
  if (score < MIN_SCORE) {
    return json({ success: false, error: 'Security check failed. Please try again.' }, 200);
  }

  // A mismatched action suggests a token generated elsewhere (e.g. on
  // Google's own demo page) being replayed here rather than genuinely
  // generated by this form.
  if (expectedAction && result.action && result.action !== expectedAction) {
    return json({ success: false, error: 'Security check failed. Please try again.' }, 200);
  }

  // Defense in depth: reject tokens issued for a completely different site.
  // Google's own domain allowlist (set when the key is created) is the
  // primary control here — this just catches a token replayed from
  // somewhere unexpected onto this endpoint.
  const hostname = result.hostname || '';
  const hostOk = ALLOWED_HOSTS.some((re) => re.test(hostname));
  if (!hostOk) {
    return json({ success: false, error: 'Security check failed. Please try again.' }, 200);
  }

  return json({ success: true }, 200);
};

function json(body, status) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json' },
  });
}

export const config = { path: '/api/verify-recaptcha' };
